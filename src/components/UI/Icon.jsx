// Size scale mapping according to specification
const SIZE_MAP = {
  xs: 14,
  sm: 16,
  md: 18,
  lg: 20,
  xl: 24,
  '2xl': 28,
  '3xl': 32,
};

/**
 * Centralized SVG Icon Component
 * Enforces visual weight, stroke width, currentColor inheritance, and accessibility.
 */
export const Icon = ({
  name,
  size = 'md',
  strokeWidth = 2,
  className = '',
  color = 'currentColor',
  ariaLabel,
  ariaHidden = true,
  spin = false,
  ...props
}) => {
  if (!name) return null;

  const normalizedKey = String(name).trim().toLowerCase().replace(/\s+/g, '-');
  const Component = ICON_REGISTRY[normalizedKey] || ICON_REGISTRY[normalizedKey.replace(/-/g, '')] || Workflow;

  // Resolve numeric pixel size
  const pixelSize = typeof size === 'number' ? size : SIZE_MAP[size] || 18;

  const spinClass = spin ? 'animate-spin' : '';
  const combinedClassName = `shrink-0 ${spinClass} ${className}`.trim();

  const accessibilityProps = ariaLabel
    ? { role: 'img', 'aria-label': ariaLabel, 'aria-hidden': false }
    : { 'aria-hidden': ariaHidden };

  return (
    <Component
      size={pixelSize}
      strokeWidth={strokeWidth}
      color={color}
      className={combinedClassName}
      {...accessibilityProps}
      {...props}
    />
  );
};

export default Icon;
